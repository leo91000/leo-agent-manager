  await page.getByRole('group', { name: 'Run view' }).getByRole('button', { name: /^Files/ }).click()
  await expect(page.getByText('No files published yet.')).toBeVisible()
  await page.getByRole('button', { name: 'Result', exact: true }).click()
  await expect(page.locator('.result-content')).toBeVisible()
