  await page.getByRole('textbox', { name: 'Search missions' }).fill('Graphile')
  await page.getByRole('button', { name: new RegExp(task.name) }).click()
  await expect(page.getByRole('button', { name: 'Choose mission' })).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('region', { name: 'Activity output' })).toBeVisible()
